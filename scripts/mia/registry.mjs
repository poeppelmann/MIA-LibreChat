import yaml from 'js-yaml';
import { join, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const TYPES = ['feature', 'fix', 'branding', 'infra'];
const STATUSES = ['active', 'adapted', 'removed'];
const KINDS = ['added', 'changed', 'fixed', 'adapted', 'removed', 'kept', 'baseline'];
const KIND_TITLES = {
  added: 'Added',
  changed: 'Changed',
  fixed: 'Fixed',
  adapted: 'Adapted to upstream',
  removed: 'Removed',
  kept: 'Unchanged after upstream update',
  baseline: 'Baseline (existing when the registry was introduced)',
};
const JIRA = /^MIA-\d+$/;
const MIA_VERSION = /^\d+\.\d+\.\d+$/;
const BASE_VERSION = /^v\d+\.\d+\.\d+$/;
const CHECK_LINE = /^(?:(contains) (.+?) => (.+)|(exists|differs) (.+))$/;
const GENERATED =
  '<!-- Generated by scripts/mia/registry.mjs. Do not edit; edit docs/mia/customizations/*.md and run `npm run mia:generate`. -->';

const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

const paths = (root) => ({
  version: join(root, 'docs', 'mia', 'VERSION'),
  entries: join(root, 'docs', 'mia', 'customizations'),
  overview: join(root, 'docs', 'mia', 'OVERVIEW.md'),
  changelog: join(root, 'CHANGELOG-MIA.md'),
  pkg: join(root, 'package.json'),
});

const compareVersions = (a, b) => {
  const [x, y] = [a, b].map((v) => v.replace(/^v/, '').split('.').map(Number));
  return x.reduce((acc, n, i) => acc || n - y[i], 0);
};

const parseEntry = (text, slug) => {
  const match = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) {
    throw new Error(`${slug}: front matter missing`);
  }
  return { slug, ...yaml.load(match[1]), body: match[2].trim() };
};

export const loadEntries = (root) => {
  const dir = paths(root).entries;
  return readdirSync(dir)
    .filter((name) => name.endsWith('.md'))
    .sort()
    .map((name) => parseEntry(readFileSync(join(dir, name), 'utf8'), name.replace(/\.md$/, '')));
};

export const readVersion = (root) => readFileSync(paths(root).version, 'utf8').trim();

const parseCheck = (line) => {
  const m = CHECK_LINE.exec(line);
  if (!m) {
    return null;
  }
  return m[1] ? { op: 'contains', path: m[2], text: m[3] } : { op: m[4], path: m[5] };
};

const latestChange = (entry) =>
  entry.changes.reduce((best, c) => (compareVersions(c.mia, best.mia) > 0 ? c : best));

const validateChange = (entry, change, index) => {
  const at = `${entry.slug} changes[${index}]`;
  return [
    !MIA_VERSION.test(change.mia ?? '') && `${at}: mia must look like 2.3.0`,
    !BASE_VERSION.test(change.base ?? '') && `${at}: base must look like v0.8.7`,
    !KINDS.includes(change.kind) && `${at}: kind must be one of ${KINDS.join(', ')}`,
    change.kind !== 'baseline' &&
      !JIRA.test(change.jira ?? '') &&
      `${at}: jira must look like MIA-254`,
    !change.note && `${at}: note is required`,
  ];
};

export const validateEntry = (entry, version) => {
  const changes = Array.isArray(entry.changes) ? entry.changes : [];
  const checks = Array.isArray(entry.checks) ? entry.checks : [];
  const files = Array.isArray(entry.files) ? entry.files : [];
  const slugOk = entry.jira ? entry.slug === entry.jira : entry.slug.startsWith('baseline-');
  const changeErrors = changes.flatMap((c, i) => validateChange(entry, c, i));
  const newerThanRelease = changes.filter(
    (c) => MIA_VERSION.test(c.mia ?? '') && compareVersions(c.mia, version) > 0,
  );
  const removedNow =
    changes.length > 0 && !changeErrors.some(Boolean) && latestChange(entry).kind === 'removed';

  return [
    !slugOk &&
      `${entry.slug}: file name must equal the Jira key, or start with "baseline-" when jira is empty`,
    entry.jira && !JIRA.test(entry.jira) && `${entry.slug}: jira must look like MIA-254`,
    !entry.title && `${entry.slug}: title is required`,
    !TYPES.includes(entry.type) && `${entry.slug}: type must be one of ${TYPES.join(', ')}`,
    !STATUSES.includes(entry.status) &&
      `${entry.slug}: status must be one of ${STATUSES.join(', ')}`,
    entry.status !== 'removed' &&
      !entry.valid_until &&
      `${entry.slug}: valid_until (removal condition) is required`,
    files.length === 0 && `${entry.slug}: files must list at least one path`,
    changes.length === 0 && `${entry.slug}: changes must list at least one entry`,
    ...checks
      .filter((line) => !parseCheck(line))
      .map((line) => `${entry.slug}: unparsable check "${line}"`),
    ...changeErrors,
    ...newerThanRelease.map(
      (c) => `${entry.slug}: change ${c.mia} is newer than docs/mia/VERSION ${version}`,
    ),
    removedNow &&
      entry.status !== 'removed' &&
      `${entry.slug}: latest change is "removed" but status is "${entry.status}"`,
    entry.status === 'removed' &&
      changes.length > 0 &&
      !removedNow &&
      `${entry.slug}: status is "removed" but latest change is not`,
  ].filter(Boolean);
};

export const validate = (root) => {
  const version = readVersion(root);
  const versionErrors = MIA_VERSION.test(version)
    ? []
    : [`docs/mia/VERSION "${version}" must look like 2.3.0`];
  const entries = loadEntries(root);
  const duplicates = entries.filter(
    (e, i) => e.jira && entries.findIndex((o) => o.jira === e.jira) !== i,
  );
  return [
    ...versionErrors,
    ...entries.flatMap((e) => validateEntry(e, version)),
    ...duplicates.map((e) => `${e.slug}: Jira key used by more than one entry`),
  ];
};

const gitRef = (tag) => `refs/tags/${tag}`;

const git = (root, args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' });

const runCheck = (root, tag, check) => {
  const file = join(root, check.path);
  if (!existsSync(file)) {
    return `${check.path} is missing${check.text ? ` (expected: ${check.text})` : ''}`;
  }
  if (check.op === 'contains') {
    return readFileSync(file, 'utf8').includes(check.text)
      ? null
      : `${check.path} does not contain: ${check.text}`;
  }
  if (check.op === 'differs') {
    const same = git(root, ['diff', '--name-only', gitRef(tag), '--', check.path]).trim() === '';
    return same ? `${check.path} is identical to ${tag} (branding lost)` : null;
  }
  return null;
};

export const check = (root, tag) => {
  git(root, ['rev-parse', '--verify', '--quiet', gitRef(tag)]);
  const results = loadEntries(root)
    .filter((e) => e.status !== 'removed')
    .flatMap((e) => (e.checks ?? []).map((line) => ({ slug: e.slug, check: parseCheck(line) })))
    .map(({ slug, check: c }) => ({ slug, error: runCheck(root, tag, c) }));
  const failures = results.filter((r) => r.error);
  return { ok: results.length - failures.length, failures };
};

const parseNameStatus = (output) =>
  output
    .split('\n')
    .filter(Boolean)
    .map((line) => line.split('\t'))
    .map(([status, from, to]) => ({ status: status[0], paths: [from, to].filter(Boolean) }));

export const review = (root, oldTag, newTag) => {
  const changed = parseNameStatus(
    git(root, ['diff', '--name-status', '-M', gitRef(oldTag), gitRef(newTag)]),
  );
  return loadEntries(root)
    .filter((e) => e.status !== 'removed')
    .map((e) => {
      const owned = new Set([
        ...(e.files ?? []),
        ...(e.checks ?? [])
          .map(parseCheck)
          .filter(Boolean)
          .map((c) => c.path),
      ]);
      const touched = changed.filter((c) => c.paths.some((p) => owned.has(p)));
      return { slug: e.slug, title: e.title, touched };
    });
};

export const release = (root) => {
  const version = readVersion(root);
  const librechat = JSON.parse(readFileSync(paths(root).pkg, 'utf8')).version;
  const bases = [
    ...new Set(
      loadEntries(root)
        .flatMap((e) => e.changes)
        .filter((c) => c.mia === version)
        .map((c) => c.base),
    ),
  ];
  const errors = [
    bases.length === 0 &&
      `no registry change is recorded for MIA ${version}; add a "changes" entry before releasing`,
    bases.length > 1 && `MIA ${version} maps to more than one LibreChat base: ${bases.join(', ')}`,
    bases.length === 1 &&
      bases[0] !== librechat &&
      `registry says MIA ${version} is based on ${bases[0]}, but package.json is ${librechat}`,
  ].filter(Boolean);
  return { mia: version, librechat, errors };
};

const bullet = (ticket, title, note) => `- **${ticket}** ${title}: ${note}`;

export const renderChangelog = (entries) => {
  const rows = entries.flatMap((e) => e.changes.map((c) => ({ ...c, title: e.title })));
  const versions = [...new Set(rows.map((r) => r.mia))].sort((a, b) => compareVersions(b, a));
  const mapping = versions.map((v) => {
    const bases = [...new Set(rows.filter((r) => r.mia === v).map((r) => r.base))];
    return `| ${v} | ${bases.join(', ')} |`;
  });
  const sections = versions.map((v) => {
    const inVersion = rows.filter((r) => r.mia === v);
    const bases = [...new Set(inVersion.map((r) => r.base))].join(', ');
    const groups = KINDS.filter((k) => inVersion.some((r) => r.kind === k)).map((k) => {
      const lines = inVersion
        .filter((r) => r.kind === k)
        .map((r) => bullet(r.jira ?? 'baseline', r.title, r.note));
      return [`### ${KIND_TITLES[k]}`, ...lines, ''].join('\n');
    });
    return [`## MIA ${v} (LibreChat ${bases})`, '', ...groups].join('\n');
  });
  return [
    GENERATED,
    '',
    '# MIA Changelog',
    '',
    'Customizations of MIA compared to upstream LibreChat, by MIA release.',
    '',
    '| MIA | LibreChat base |',
    '|---|---|',
    ...mapping,
    '',
    ...sections,
  ].join('\n');
};

export const renderOverview = (entries) => {
  const rows = entries.map((e) => {
    const latest = latestChange(e);
    const since = e.changes.reduce(
      (min, c) => (compareVersions(c.mia, min) < 0 ? c.mia : min),
      e.changes[0].mia,
    );
    const until = e.status === 'removed' ? latest.mia : '-';
    const ticket = e.jira ?? 'baseline';
    return `| ${ticket} | [${e.title}](customizations/${e.slug}.md) | ${e.type} | ${e.status} | ${since} | ${until} | ${e.valid_until ?? '-'} | ${latest.mia} (${latest.base}) |`;
  });
  return [
    GENERATED,
    '',
    '# MIA customizations',
    '',
    '| Ticket | Customization | Type | Status | Since MIA | Removed in MIA | Valid until | Last reviewed |',
    '|---|---|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
};

export const generate = (root, { verify = false } = {}) => {
  const entries = loadEntries(root);
  const p = paths(root);
  const outputs = [
    [p.overview, renderOverview(entries)],
    [p.changelog, `${renderChangelog(entries)}\n`],
  ];
  const stale = outputs.filter(
    ([file, content]) => !existsSync(file) || readFileSync(file, 'utf8') !== content,
  );
  if (verify) {
    return stale.map(([file]) => file.replace(`${root}/`, ''));
  }
  stale.forEach(([file, content]) => writeFileSync(file, content));
  return [];
};

const printErrors = (errors) => errors.forEach((e) => console.error(`FAIL ${e}`));

const commands = {
  validate: (root) => {
    const errors = validate(root);
    printErrors(errors);
    console.log(`Registry validation: ${errors.length === 0 ? 'ok' : `${errors.length} error(s)`}`);
    return errors.length === 0 ? 0 : 1;
  },
  generate: (root, args) => {
    const verify = args.includes('--check');
    const stale = generate(root, { verify });
    stale.forEach((f) => console.error(`FAIL ${f} is out of date; run npm run mia:generate`));
    return stale.length === 0 ? 0 : 1;
  },
  check: (root, [tag]) => {
    if (!tag) {
      console.error('usage: registry.mjs check <upstream-tag>');
      return 2;
    }
    const { ok, failures } = check(root, tag);
    failures.forEach((f) => console.error(`FAIL [${f.slug}] ${f.error}`));
    console.log(`Customization check against ${tag}: ${ok} ok, ${failures.length} failed`);
    return failures.length === 0 ? 0 : 1;
  },
  review: (root, [oldTag, newTag]) => {
    if (!oldTag || !newTag) {
      console.error('usage: registry.mjs review <old-tag> <new-tag>');
      return 2;
    }
    const result = review(root, oldTag, newTag);
    const touched = result.filter((r) => r.touched.length > 0);
    touched.forEach((r) => {
      console.log(`REVIEW [${r.slug}] ${r.title}`);
      r.touched.forEach((t) => console.log(`    ${t.status} ${t.paths.join(' -> ')}`));
    });
    console.log(
      `${touched.length} of ${result.length} customizations touch files changed upstream (${oldTag}..${newTag}); the rest are unaffected.`,
    );
    return 0;
  },
  release: (root) => {
    const { mia, librechat, errors } = release(root);
    printErrors(errors);
    if (errors.length === 0) {
      console.log(`mia=${mia}`);
      console.log(`librechat=${librechat}`);
    }
    return errors.length === 0 ? 0 : 1;
  },
};

const main = () => {
  const [command, ...args] = process.argv.slice(2);
  const run = commands[command];
  if (!run) {
    console.error(`usage: registry.mjs <${Object.keys(commands).join('|')}> [args]`);
    process.exit(2);
  }
  process.exit(run(rootDir, args));
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
